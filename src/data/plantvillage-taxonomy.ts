/**
 * Unified taxonomy: 38 official PlantVillage benchmark classes + extended pests & weeds.
 */
export const ALL_TAXONOMY: Record<string, PlantVillageClassDef> = {
  ...PLANTVILLAGE_TAXONOMY,
  ...EXTENDED_PEST_WEED_TAXONOMY,
};

/**
 * Get definition by exact class key from either benchmark or extended pest/weed taxonomy.
 */
export function getPlantVillageDef(key: string): PlantVillageClassDef | undefined {
  const def = ALL_TAXONOMY[key] ?? PLANTVILLAGE_TAXONOMY[key];
  if (!def) return undefined;
  return {
    ...def,
    isHealthy: def.severity === 'healthy',
  };
}

/**
 * Find definition by query string across all known plant diseases, pests, and weeds.
 */
export function findPlantVillageDef(query: string): PlantVillageClassDef | undefined {
  if (!query) return undefined;
  const q = query.toLowerCase().trim();

  // Exact key match
  if (ALL_TAXONOMY[query]) {
    return getPlantVillageDef(query);
  }

  for (const def of Object.values(ALL_TAXONOMY)) {
    if (
      def.key.toLowerCase() === q ||
      def.conditionRu.toLowerCase().includes(q) ||
      def.conditionEn.toLowerCase().includes(q) ||
      (def.latinName && def.latinName.toLowerCase().includes(q))
    ) {
      return {
        ...def,
        isHealthy: def.severity === 'healthy',
      };
    }
  }

  return undefined;
}

